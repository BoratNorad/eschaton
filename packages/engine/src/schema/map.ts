import { z } from "zod";
import { NonNegInt, PosInt, Slug } from "./primitives.js";

export const Terrain = z.enum(["plains", "mountain", "desert", "urban", "forest", "jungle", "arctic", "sea"]);

export const Region = z
  .object({
    id: Slug,
    name: z.string().min(1),
    /** Nation id of the starting controller; sea regions use "none". */
    controller: Slug,
    terrain: Terrain,
    /**
     * [lat, lon] in degrees. DISPLAY AND TOOLING ONLY: the engine never reads this.
     * tools/build-distances.ts turns centroids into the integer greatCircleKm table.
     */
    displayCentroid: z.tuple([z.number().min(-90).max(90), z.number().min(-180).max(180)]),
  })
  .strict();
export type Region = z.infer<typeof Region>;

export const RegionLink = z
  .object({
    from: Slug,
    to: Slug,
    mode: z.enum(["land", "sea", "air"]),
    /** Movement cost in turns for a standard force. */
    moveTurns: PosInt,
  })
  .strict();
export type RegionLink = z.infer<typeof RegionLink>;

export const WorldMap = z
  .object({
    id: Slug,
    name: z.string().min(1),
    regions: z.array(Region).min(1),
    links: z.array(RegionLink),
    /**
     * GENERATED by tools/build-distances.ts; never hand-edit.
     * Key "a|b" with a < b; value in whole km. Used for delivery range checks.
     */
    greatCircleKm: z.record(z.string().regex(/^[a-z0-9_]+\|[a-z0-9_]+$/), NonNegInt).default({}),
  })
  .strict();
export type WorldMap = z.infer<typeof WorldMap>;
